"""Generate src/gen/fconst.asm: the constants of the float library.

Extended constants (64-bit mantissa, for the math functions) are 10 bytes each: the
exponent word, then the mantissa (little-endian, bit 63 set); value = m * 2^(e - 63).
Constant FK_x is the index for f_const. Doubles (math.pi and so on) are 8 bytes.
"""
import os
import struct
from decimal import Decimal, getcontext
from fractions import Fraction

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
getcontext().prec = 80


def pi_decimal():
    # Machin: pi = 16 atan(1/5) - 4 atan(1/239)
    def atan_inv(n):
        x = Decimal(1) / n
        x2 = x * x
        s, t, k = Decimal(0), x, 1
        while True:
            term = t / k
            if term == 0 or abs(term) < Decimal(10) ** -78:
                break
            s += term if (k // 2) % 2 == 0 else -term
            t *= x2
            k += 2
        return s
    return 16 * atan_inv(5) - 4 * atan_inv(239)


def ext(value):
    """Fraction or Decimal -> (exp, 64-bit mantissa), rounded to nearest."""
    f = Fraction(value)
    assert f > 0
    e = 0
    while f >= 2:
        f /= 2
        e += 1
    while f < 1:
        f *= 2
        e -= 1
    m = round(f * 2 ** 63)
    if m == 2 ** 64:
        m //= 2
        e += 1
    return e, m


def trunc_bits(value, frac_bits):
    f = Fraction(value)
    return Fraction(int(f * 2 ** frac_bits), 2 ** frac_bits)


def main():
    PI = Fraction(pi_decimal())
    LN2 = Fraction(Decimal(2).ln())
    LN10 = Fraction(Decimal(10).ln())
    E = Fraction(Decimal(1).exp())
    PIO2 = PI / 2
    consts = []                                 # (name, value)
    for n in range(1, 37):
        consts.append(("RECIP%d" % n, Fraction(1, n)))
    ln2_hi = trunc_bits(LN2, 52)
    pio2_hi = trunc_bits(PIO2, 33)
    pio2_mid = trunc_bits(PIO2 - pio2_hi, 66)
    consts += [
        ("LN2", LN2), ("LN2_HI", ln2_hi), ("LN2_LO", LN2 - ln2_hi),
        ("INV_LN2", 1 / LN2), ("INV_LN10", 1 / LN10),
        ("PIO2", PIO2), ("PIO2_HI", pio2_hi), ("PIO2_MID", pio2_mid),
        ("PIO2_LO", PIO2 - pio2_hi - pio2_mid), ("TWO_OVER_PI", 2 / PI),
        ("PI", PI), ("SQRT2", Fraction(Decimal(2).sqrt())),
    ]
    out = [";" + "=" * 86, "; GENERATED by tools/gen_fconst.py - do not edit",
           ";" + "=" * 86]
    for i, (name, _) in enumerate(consts):
        out.append("FK_%-20s= %d" % (name, i))
    out.append("fconst:")
    for name, v in consts:
        e, m = ext(v)
        b = m.to_bytes(8, "little")
        out.append("        .sint %d\n        .byte %s    ; %s" %
                   (e, ", ".join("$%02x" % x for x in b), name))
    doubles = [("PI", float(PI)), ("E", float(E)), ("TAU", float(2 * PI)),
               ("INF", float("inf")), ("NAN", float("nan")),
               ("DEGREES", 180.0 / float(PI)), ("RADIANS", float(PI) / 180.0)]
    for i, (name, _) in enumerate(doubles):
        out.append("FD_%-20s= %d" % (name, i))
    out.append("fdoubles:")
    for name, v in doubles:
        b = struct.pack("<d", v)
        out.append("        .byte %s    ; %s" % (", ".join("$%02x" % x for x in b), name))
    os.makedirs(os.path.join(ROOT, "src", "gen"), exist_ok=True)
    with open(os.path.join(ROOT, "src", "gen", "fconst.asm"), "w") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
